function geo_is_country(string $value): bool {
    return in_array($value, GEO_COUNTRIES, true);
}

function geo_is_province(string $value): bool {
    return isset(GEO_IRAN_PROVINCES[$value]);
}

/** True when $city is listed — under $province when one is given, under any province otherwise. */
function geo_is_city(string $city, ?string $province = null): bool {
    if ($province !== null && $province !== '') {
        return in_array($city, GEO_IRAN_PROVINCES[$province] ?? [], true);
    }
    foreach (GEO_IRAN_PROVINCES as $cities) {
        if (in_array($city, $cities, true)) return true;
    }
    return false;
}

/** Renders <option>s, plus the stored value as an extra option when it predates the fixed list. */
function geo_options(array $values, string $current, string $placeholder): string {
    $h = '<option value="">' . e($placeholder) . '</option>';
    if ($current !== '' && !in_array($current, $values, true)) {
        $h .= '<option value="' . e($current) . '" selected>' . e($current) . '</option>';
    }
    foreach ($values as $value) {
        $h .= '<option value="' . e($value) . '"' . ($value === $current ? ' selected' : '') . '>' . e($value) . '</option>';
    }
    return $h;
}

function geo_country_select(string $name, string $current, string $attrs = ''): string {
    return '<select name="' . e($name) . '" data-geo="country" ' . $attrs . '>'
        . geo_options(GEO_COUNTRIES, $current, 'انتخاب کشور') . '</select>';
}

function geo_province_select(string $name, string $current, string $attrs = ''): string {
    return '<select name="' . e($name) . '" data-geo="province" ' . $attrs . '>'
        . geo_options(array_keys(GEO_IRAN_PROVINCES), $current, 'انتخاب استان') . '</select>' . geo_data_script();
}

/** Cities of $province, server-rendered so the field works before (or without) JavaScript. */
function geo_city_select(string $name, string $current, string $province, string $attrs = ''): string {
    $cities = GEO_IRAN_PROVINCES[$province] ?? [];
    return '<select name="' . e($name) . '" data-geo="city" ' . $attrs . '>'
        . geo_options($cities, $current, $cities ? 'انتخاب شهر' : 'ابتدا استان را انتخاب کنید') . '</select>';
}

/** Every listed city, grouped by province — for a city asked on its own (e.g. place of birth). */
function geo_any_city_select(string $name, string $current, string $attrs = ''): string {
    $h = '<select name="' . e($name) . '" ' . $attrs . '><option value="">انتخاب شهر</option>';
    if ($current !== '' && !geo_is_city($current)) {
        $h .= '<option value="' . e($current) . '" selected>' . e($current) . '</option>';
    }
    foreach (GEO_IRAN_PROVINCES as $province => $cities) {
        $h .= '<optgroup label="' . e($province) . '">';
        foreach ($cities as $city) {
            $h .= '<option value="' . e($city) . '"' . ($city === $current ? ' selected' : '') . '>' . e($city) . '</option>';
        }
        $h .= '</optgroup>';
    }
    return $h . '</select>';
}

/** The province→cities map for assets/js/forms.js, emitted once per page. */
function geo_data_script(): string {
    static $emitted = false;
    if ($emitted) return '';
    $emitted = true;
    $json = json_encode(GEO_IRAN_PROVINCES, JSON_UNESCAPED_UNICODE | JSON_HEX_TAG | JSON_HEX_AMP);
    return '<script type="application/json" id="geoIranData">' . $json . '</script>';
}
