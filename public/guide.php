<script>
(function(){
  const input=document.getElementById('guideSearch');
  if(!input) return;
  const items=[...document.querySelectorAll('.guide-item[data-guide-text]')];
  input.addEventListener('input',function(){
    const q=this.value.trim().toLocaleLowerCase('fa');
    items.forEach(function(item){
      const text=(item.dataset.guideText||'').toLocaleLowerCase('fa');
      const show=!q||text.includes(q);
      item.classList.toggle('guide-hidden',!show);
      if(q&&show) item.open=true;
    });
  });
})();
</script>
